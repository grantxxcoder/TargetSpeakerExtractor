"""Draws the report's voice-picking figure: how often each extractor follows the voice it is asked for, for same-gender and different-gender pairs.

    ../tse_venv/bin/python scripts/plot_voice_picking.py --out report/figures/voice_picking.pdf

Each two-voice validation crop (sir0_val, both speakers live) is run twice, once with each speaker's enrolment. A run lands on the requested voice when its output is nearer, by SI-SDR, the stem that was asked for than the other stem, the rule of scripts/diagnose_cue_directional.py (in git before 759ec7a). Each crop therefore gives two decisions, and 50 % is a coin flip.
The per-crop results come from experiments/results/2026-09-22-cue-directional-sir0 (baseline checkpoint 10000-e6, an earlier checkpoint of the same architecture as the matched baseline e11, which was never measured this way) and 2026-09-26-cue-directional-sir0-cuecontext-wer-e21 (the extension).
The 95 % intervals redraw whole crops, so a crop's two decisions stay together (10,000 draws, seed 42). The change from baseline to extension is paired over the same crops.
The rates, intervals and paired changes are written to experiments/results/2026-10-28-voice-picking-ci/.
Claude Code wrote this script from the author's figure specification (2026-10-28).
"""

import argparse
import csv
import json
import subprocess
from datetime import date
from pathlib import Path

import matplotlib as mpl
import matplotlib.pyplot as plt
import numpy as np
from matplotlib.patches import Patch

# The figure is written straight to a file, without a screen.
mpl.use("Agg")

# House style for every report figure, copied from scripts/plot_training_curves.py. Generated by Claude Code
mpl.rcParams.update({
    "font.family": "serif",
    "font.serif": ["Times New Roman", "Nimbus Roman", "DejaVu Serif"],
    "font.size": 9, "axes.labelsize": 9, "axes.titlesize": 9,
    "xtick.labelsize": 8, "ytick.labelsize": 8, "legend.fontsize": 8,
    "axes.linewidth": 0.6, "xtick.major.width": 0.6, "ytick.major.width": 0.6,
    "axes.spines.top": False, "axes.spines.right": False,
    "figure.dpi": 140, "savefig.dpi": 300,
    "savefig.bbox": "tight", "savefig.pad_inches": 0.01, "pdf.fonttype": 42,
    "mathtext.fontset": "stix",
})
FIGURE_WIDTH_IN = 3.4
FIGURE_HEIGHT_IN = 2.4
INK = "#222222"
BLUE = "#0B6E99"
ORANGE = "#C1440E"
MUTED = "#6B6B6B"

REPO_ROOT = Path(__file__).resolve().parents[1]
RESULTS = REPO_ROOT / "experiments/results"
OUT_DIRECTORY = RESULTS / "2026-10-28-voice-picking-ci"

# The two systems drawn, with their per-crop result folders and colours.
SYSTEMS = [
    ("Baseline", RESULTS / "2026-09-22-cue-directional-sir0/per_pair.csv", ORANGE),
    ("Extension", RESULTS / "2026-09-26-cue-directional-sir0-cuecontext-wer-e21/per_pair.csv", BLUE),
]

# The two groups of pairs, by the value of the same_gender column.
GROUPS = [("Same gender", "1.0"), ("Different gender", "0.0")]

DRAWS = 10000
SEED = 42


# this reads, for one system, each two-voice crop's number of right decisions (0, 1 or 2) by trial id and gender group
def read_right_decisions(path):
    right = {}
    with open(path, newline="") as handle:
        for row in csv.DictReader(handle):
            if row["target_live"] != "True" or row["interferer_live"] != "True":
                continue
            count = 0
            if float(row["sisdr_yt_st"]) > float(row["sisdr_yt_si"]):
                count += 1
            if float(row["sisdr_yi_si"]) > float(row["sisdr_yi_st"]):
                count += 1
            right[row["trial_id"]] = (row["same_gender"], count)
    return right


# this gives the rate, its 95 % interval over crops, and the paired change from the first system to the second, for each gender group
def summarise(per_system):
    generator = np.random.default_rng(SEED)
    names = []
    for name, path, colour in SYSTEMS:
        names.append(name)
    summary = {}
    for group_name, group_value in GROUPS:
        trial_ids = []
        for trial_id, (gender, count) in per_system[names[0]].items():
            if gender == group_value:
                trial_ids.append(trial_id)
        trial_ids.sort()
        for name in names[1:]:
            for trial_id in trial_ids:
                if trial_id not in per_system[name]:
                    raise SystemExit(f"{name} has no result for {trial_id}, so the change cannot be paired.")
        counts = {}
        for name in names:
            group_counts = []
            for trial_id in trial_ids:
                group_counts.append(per_system[name][trial_id][1])
            counts[name] = np.array(group_counts)
        # Whole crops are redrawn, the same draws for both systems, so the change is paired.
        draws = generator.integers(0, len(trial_ids), size=(DRAWS, len(trial_ids)))
        group_summary = {"crops": len(trial_ids), "decisions": 2 * len(trial_ids)}
        for name in names:
            rate = 100.0 * counts[name].sum() / (2 * len(trial_ids))
            resampled = 100.0 * counts[name][draws].sum(axis=1) / (2 * len(trial_ids))
            group_summary[name] = {"right": int(counts[name].sum()), "rate_pct": round(rate, 2), "ci95_pct": [round(float(np.percentile(resampled, 2.5)), 2), round(float(np.percentile(resampled, 97.5)), 2)]}
        change = 100.0 * (counts[names[1]] - counts[names[0]])[draws].sum(axis=1) / (2 * len(trial_ids))
        group_summary["change_pp"] = round(group_summary[names[1]]["rate_pct"] - group_summary[names[0]]["rate_pct"], 2)
        group_summary["change_ci95_pp"] = [round(float(np.percentile(change, 2.5)), 2), round(float(np.percentile(change, 97.5)), 2)]
        summary[group_name] = group_summary
    return summary


# this draws one group of bars per gender group, with each bar's 95 % interval and value, and the coin-flip line
def draw(summary, output_path):
    figure, axis = plt.subplots(figsize=(FIGURE_WIDTH_IN, FIGURE_HEIGHT_IN))
    bar_width = 0.34
    tick_labels = []
    for position, (group_name, group_value) in enumerate(GROUPS):
        group = summary[group_name]
        for index, (name, path, colour) in enumerate(SYSTEMS):
            x = position + (index - 0.5) * bar_width
            rate = group[name]["rate_pct"]
            low, high = group[name]["ci95_pct"]
            axis.bar(x, rate, width=bar_width * 0.9, color=colour, linewidth=0)
            axis.errorbar(x, rate, yerr=[[rate - low], [high - rate]], color=INK, linewidth=0.7, capsize=2, capthick=0.7)
            axis.text(x, high + 1.5, f"{rate:.1f}", fontsize=7.5, color=INK, ha="center", va="bottom")
        tick_labels.append(f"{group_name}\n({group['crops']} pairs)")
    axis.axhline(50.0, color=MUTED, linestyle="--", linewidth=0.8, zorder=0)
    axis.text(1.62, 50.0, "coin flip", fontsize=7.5, color=MUTED, ha="right", va="bottom")
    axis.set_xticks(range(len(GROUPS)))
    axis.set_xticklabels(tick_labels)
    axis.tick_params(axis="x", length=0)
    axis.set_xlim(-0.55, len(GROUPS) - 0.45)
    axis.set_ylim(0, 108)
    axis.set_yticks([0, 25, 50, 75, 100])
    axis.set_ylabel("Requested voice picked (%)")
    handles = []
    for name, path, colour in SYSTEMS:
        handles.append(Patch(facecolor=colour, label=name))
    axis.legend(handles=handles, loc="upper left", frameon=False, handlelength=1.2)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(output_path)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default="report/figures/voice_picking.pdf")
    arguments = parser.parse_args()
    per_system = {}
    for name, path, colour in SYSTEMS:
        per_system[name] = read_right_decisions(path)
    summary = summarise(per_system)
    sources = {}
    for name, path, colour in SYSTEMS:
        sources[name] = str(path.relative_to(REPO_ROOT))
    record = {"date": date.today().isoformat(), "git_commit": subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True, cwd=REPO_ROOT).stdout.strip(), "seed": SEED, "draws": DRAWS, "rule": "a run lands on the requested voice when SI-SDR to the requested stem exceeds SI-SDR to the other stem; two decisions per two-voice crop", "interval": "percentile bootstrap over whole crops, same draws for both systems (paired change)", "sources": sources, "groups": summary}
    OUT_DIRECTORY.mkdir(parents=True, exist_ok=True)
    with open(OUT_DIRECTORY / "summary.json", "w") as handle:
        json.dump(record, handle, indent=2)
    draw(summary, Path(arguments.out))
    # Generated by Claude Code
    print(f"wrote {arguments.out} and {OUT_DIRECTORY / 'summary.json'}")
    for group_name, group in summary.items():
        line = f"  {group_name:<17} {group['crops']} crops"
        for name, path, colour in SYSTEMS:
            line += f"  {name} {group[name]['rate_pct']:.1f} % [{group[name]['ci95_pct'][0]:.1f}, {group[name]['ci95_pct'][1]:.1f}]"
        line += f"  change {group['change_pp']:+.1f} pp [{group['change_ci95_pp'][0]:+.1f}, {group['change_ci95_pp'][1]:+.1f}]"
        print(line)


if __name__ == "__main__":
    main()
