def build_loss_settings(config):
    """Read the loss weights and floors from the config into one dictionary.

    It is a dictionary so the training loop can update the absent weight w at every step of its schedule.
    """
    absent_weight = float(config["loss"]["w"])
    multi_resolution_weight = float(config["loss"]["w_m"])
    present_floor = float(config["loss"]["tau_pres"])
    absent_floor = float(config["loss"]["tau_abs"])
    compression_exponent = float(config["loss"]["p"])
    window_lengths_ms = tuple(config["loss"]["windows_ms"])
    # The sample rate turns the window lengths from milliseconds into samples.
    sample_rate = int(config["data"]["sample_rate"])
    gain_weight = float(config["loss"]["w_g"])
    gain_deadzone_db = float(config["loss"]["gain_delta_db"])
    return {
        "absent_weight": absent_weight,
        "multi_resolution_weight": multi_resolution_weight,
        "present_floor": present_floor,
        "absent_floor": absent_floor,
        "compression_exponent": compression_exponent,
        "window_lengths_ms": window_lengths_ms,
        "sample_rate": sample_rate,
        "gain_weight": gain_weight,
        "gain_deadzone_db": gain_deadzone_db,
    }


# The absent weight w ramps up from a low start, so the model learns to use the enrolment before it learns to stay silent (decisions-m2.md 2026-08-25).
# The schedule counts optimiser steps rather than epochs, so it does not stretch when the training set grows.

def ramped_weight(start_weight, final_weight, warmup_steps, ramp_steps, step):
    """Hold start_weight through the warmup, rise in a straight line to final_weight over the ramp, then hold final_weight."""
    if step < warmup_steps:
        return start_weight
    if step >= warmup_steps + ramp_steps:
        return final_weight
    # Adding one makes the last step of the ramp land exactly on final_weight. This particular ramp function was the choice of Claude Code.
    ramp_fraction = (step - warmup_steps + 1) / ramp_steps
    return start_weight + ramp_fraction * (final_weight - start_weight)


def w_at_step(config, global_step):
    """The absent weight for this step.

    global_step counts every batch, including any the mixed-precision scaler skipped, so a rerun follows the same schedule.
    A fine-tune leaves w_schedule out: the model already learned to stay silent, and a warmup would switch the silence term off again (the 2026-10-03 fine-tunes did the same).
    """
    if "w_schedule" not in config["loss"]:
        return float(config["loss"]["w"])
    schedule = config["loss"]["w_schedule"]
    return ramped_weight(float(schedule["w_start"]), float(config["loss"]["w"]), int(schedule["warmup_steps"]), int(schedule["ramp_steps"]), global_step)


