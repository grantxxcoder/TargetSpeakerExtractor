# this wraps the model being trained so the content probe can run it on whole clips
def live_extractor(model, speaker_encoder, device):
    """Extractor over the model being trained: whole clip, one forward, the same path as make_estimates.py. Caller sets eval() and no_grad()."""
    def run(mixture, enrollment, sample_rate):
        # get the enrollment and then perform extraction!
        enrollment_tensor = torch.from_numpy(enrollment).unsqueeze(0).to(device)
        mixture_tensor = torch.from_numpy(mixture).unsqueeze(0).to(device)
        estimate = extract(model, mixture_tensor, enrollment_tensor, enrol_embedding=speaker_embedding(speaker_encoder, enrollment_tensor))
        return estimate.squeeze(0).float().cpu().numpy()
    return run


# Claude suggestion for how to keep an epoch
def checkpoints_to_drop(kept_checkpoints, keep_top_k, keep_stride, last_epoch):
    """Return the epochs whose saved weights can be deleted. kept_checkpoints is a list of (score, epoch) pairs, best first.

    The best keep_top_k epochs survive, plus every keep_stride-th epoch and the last one, because a deleted checkpoint can only be recovered by retraining (decisions-m2.md 2026-09-23).
    """
    survivors = {last_epoch}
    for score, epoch in kept_checkpoints[:keep_top_k]:
        survivors.add(epoch)
    for score, epoch in kept_checkpoints:
        if epoch % keep_stride == 0:
            survivors.add(epoch)
    to_drop = set()
    for score, epoch in kept_checkpoints:
        if epoch not in survivors:
            to_drop.add(epoch)
    return sorted(to_drop)


# this gathers everything a resume needs into one dictionary
def training_state(model, optimizer, scheduler, epoch, global_step, content_probe, best_val, best_row, config):
    return {
        "model": model.state_dict(),
        "optimizer": optimizer.state_dict(),
        "scheduler": scheduler.state_dict(),
        "epoch": epoch,
        "global_step": global_step,
        "content_wer_history": content_probe["history"],  # so the probe's smoothing survives a resume
        "best_val": best_val,
        "best_row": best_row,
        "config": config,
        "seed": config["seed"],
    }


# in this method I used Claude Code to debug and better structure the training and validation loop.
def train(model, train_loader, val_loader, optimizer, scheduler, num_epochs, device, save_path, config, content_probe, speaker_encoder, start_epoch, best_val, best_row, start_step):
    model.to(device)
    val_loss_history = []
    train_loss_history = []

    loss_settings = build_loss_settings(config)
    grad_clip = float(config["training"]["grad_clip"])
    patience = int(config["training"]["patience"])
    keep_top_k = int(config["training"]["keep_top_k"])
    keep_stride = int(config["training"]["keep_stride"])
    kept_checkpoints = []
    epochs_since_best = 0

    reporting_weight = float(config["loss"]["w"])  # every reported total uses this, so the curve is one objective
    steps_per_epoch = len(train_loader)  # the loader counts trials; training both directions widens the batches, not the epoch
    # Generated by Claude Code
    if "w_schedule" in config["loss"]:
        schedule = config["loss"]["w_schedule"]
        print(f"  w schedule: {schedule['w_start']} for {schedule['warmup_steps']} steps, then a ramp to {reporting_weight} over {schedule['ramp_steps']} steps, at {steps_per_epoch} steps per epoch", flush=True)
    else:
        print(f"  w held at {reporting_weight} from the first step (no w_schedule, a fine-tune), at {steps_per_epoch} steps per epoch", flush=True)

    # Mixed precision runs only on CUDA. When it is off the scaler's calls do nothing, so one code path serves both.
    use_mixed_precision = device.type == "cuda"
    scaler = torch.amp.GradScaler("cuda", enabled=use_mixed_precision)
    print(f"  mixed precision: {'ON (fp16 forward, fp32 loss)' if use_mixed_precision else 'off'}", flush=True)

    global_step = int(start_step)  # carried across a resume so the w warmup does not restart

    for epoch in range(start_epoch, num_epochs):
        # With persistent workers this never reaches the worker copies of the dataset, so the crops, enrolments and remix stay those of the session's first epoch (found 2026-10-24).
        train_loader.dataset.set_epoch(epoch)

        model.train()
        sums, counts = defaultdict(float), defaultdict(int)
        weight_sum, weight_steps = 0.0, 0  # for the mean w that trained this epoch
        epoch_start = time.time()
        for batch in train_loader:
            loss_settings["absent_weight"] = w_at_step(config, global_step)
            weight_sum += loss_settings["absent_weight"]
            weight_steps += 1

            # first get daata from the loader so that it can be sent to the model
            mixture, target, enrollment, crop_absent = unpack(batch, device)
            # also get the embedding
            enrol_embedding = speaker_embedding(speaker_encoder, enrollment)

            optimizer.zero_grad()
            with mixed_precision(use_mixed_precision):
                output = extract(model, mixture, enrollment, enrol_embedding=enrol_embedding)
            # Reference first, then output (see bsrnn_loss). The loss runs in fp32.
            loss, parts = bsrnn_loss(target, output.float(), mixture, crop_absent, loss_settings)
            scaler.scale(loss).backward()
            # Unscale before clipping, or the clip sees gradients inflated by the loss scale (Micikevicius et al., 2018).
            scaler.unscale_(optimizer)
            nn.utils.clip_grad_norm_(model.parameters(), grad_clip)  # gradient-norm clipping (Pascanu et al., 2013)
            # step() skips updates with inf/NaN gradients; a few early skips are the scaler calibrating.
            scaler.step(optimizer)
            scaler.update()

            add_parts(sums, counts, parts)
            global_step += 1

        w_trained = weight_sum / weight_steps
        epoch_loss = epoch_report(sums, counts, reporting_weight, loss_settings["multi_resolution_weight"], loss_settings["gain_weight"])
        train_loss_history.append(epoch_loss)

        # Validation, in the same precision as training.
        model.eval()
        val_sums, val_counts = defaultdict(float), defaultdict(int)
        diagnostics = defaultdict(float)
        with torch.no_grad():
            for batch in val_loader:
                mixture, target, enrollment, crop_absent = unpack(batch, device)
                enrol_embedding = speaker_embedding(speaker_encoder, enrollment)

                with mixed_precision(use_mixed_precision):
                    output = extract(model, mixture, enrollment, enrol_embedding=enrol_embedding)
                output = output.float()
                batch_loss, parts = bsrnn_loss(target, output, mixture, crop_absent, loss_settings)
                add_parts(val_sums, val_counts, parts)
                diagnostic_accumulate(diagnostics, model, mixture, enrollment, output, crop_absent, use_mixed_precision, enrol_embedding)

            val_loss = epoch_report(val_sums, val_counts, reporting_weight, loss_settings["multi_resolution_weight"], loss_settings["gain_weight"])
            val_loss.update(diagnostic_report(diagnostics))
            # Content probe: whole clips with reference text, which the 4 s validation crops do not have.
            val_loss["content_wer"] = probe_score(content_probe, live_extractor(model, speaker_encoder, device))
        val_loss["content_wer_ema"] = content_probe["smoothed"][-1]
        val_loss["epoch"] = epoch
        val_loss["lr"] = optimizer.param_groups[0]["lr"]
        val_loss["w"] = w_trained
        val_loss_history.append(val_loss)

        # One CSV row per epoch on stdout (flushed, so a killed run keeps it), and the readable table on stderr. Generated by Claude Code.
        if epoch == start_epoch:
            print(",".join(history_header()), flush=True)
        print(",".join(str(value) for value in history_row(epoch_loss, val_loss)), flush=True)
        print(format_epoch_breakdown(epoch, num_epochs, epoch_loss, val_loss, time.time() - epoch_start, w_trained), file=sys.stderr, flush=True)

        score = selection_score(val_loss)
        scheduler.step(score)

        # The newest weights, every epoch. Not what --resume reads, which is the best checkpoint.
        torch.save(training_state(model, optimizer, scheduler, epoch, global_step, content_probe, best_val, best_row, config), Path(save_path).with_name(Path(save_path).stem + "_last.pt"))

        eligible = selection_eligible(val_loss, config)
        # Keep top-k and strided checkpoints so epochs can be re-scored on content later (see checkpoints_to_drop).
        # Not gated on `eligible`: on a run that never clears the silence bar these are the only weights that survive.
        kept_checkpoints.append((score, epoch))
        kept_checkpoints.sort()
        epoch_checkpoint_path = Path(save_path).with_name(f"{Path(save_path).stem}_e{epoch:03d}.pt")
        torch.save({"model": model.state_dict(), "epoch": epoch, "score": score, "eligible": eligible, "row": val_loss, "config": config, "seed": config["seed"]}, epoch_checkpoint_path)
        for dropped_epoch in checkpoints_to_drop(kept_checkpoints, keep_top_k, keep_stride, epoch):
            Path(save_path).with_name(f"{Path(save_path).stem}_e{dropped_epoch:03d}.pt").unlink(missing_ok=True)
            remaining = []
            for kept_score, kept_epoch in kept_checkpoints:
                if kept_epoch != dropped_epoch:
                    remaining.append((kept_score, kept_epoch))
            kept_checkpoints = remaining

        if eligible and score < best_val:
            best_val = score
            best_row = val_loss
            epochs_since_best = 0
            torch.save(training_state(model, optimizer, scheduler, epoch, global_step, content_probe, best_val, best_row, config), save_path)
        else:
            epochs_since_best += 1
            if epochs_since_best >= patience:  # early stopping: patience epochs without a new best
                print(f"Early stop at epoch {epoch}: {patience} epochs without improving on {best_val:.4f}")
                break

    # No epoch cleared the silence bar, so no best checkpoint exists. Say so rather than relax the bar.
    if best_row is None:
        print(f"WARNING: no epoch met training.select_abs_max={config['training']['select_abs_max']} on L_abs, so no best checkpoint was written. The kept epochs and _last.pt are on disk.", file=sys.stderr)

    return train_loss_history, val_loss_history, best_row


# I need this method to load the data into a loader
def get_data_loaders(manifest_dir, data_root, config):
    # chunk_s = 4 s follows CARTSE (Li & Seki, 2026).
    train_dataset = TrialDataset(manifest_dir / f"{TRAIN_SPLIT}.csv", data_root / "rendered" / TRAIN_SPLIT, config["data"]["chunk_s"], config["data"]["sample_rate"], config["seed"], True, int(config["data"]["enrollment_variants"]))
    val_dataset = TrialDataset(manifest_dir / f"{VAL_SPLIT}.csv", data_root / "rendered" / VAL_SPLIT, config["data"]["chunk_s"], config["data"]["sample_rate"], config["seed"], False, 1)

    num_workers = int(config["data"]["num_workers"])
    # Worker processes only exist when num_workers is above zero, so the two worker settings are off otherwise.
    persistent_workers = num_workers > 0
    prefetch_factor = 4 if num_workers > 0 else None
    # Pinned memory lets the copies from the CPU to the GPU run in the background.
    pin_memory = torch.cuda.is_available()

    train_loader = DataLoader(train_dataset, batch_size=config["data"]["batch_size"], shuffle=True, num_workers=num_workers, drop_last=True, collate_fn=collate_pairs, persistent_workers=persistent_workers, prefetch_factor=prefetch_factor, pin_memory=pin_memory)
    val_loader = DataLoader(val_dataset, batch_size=config["data"]["batch_size"], shuffle=False, num_workers=num_workers, collate_fn=collate_pairs, persistent_workers=persistent_workers, prefetch_factor=prefetch_factor, pin_memory=pin_memory)
    return train_loader, val_loader

