def history_header():
    # `w` is the weight that trained the epoch; `total` always uses the final w (see epoch_report).
    return ["epoch"] + [f"train_{k}" for k in HISTORY_FIELDS] + [f"val_{k}" for k in HISTORY_FIELDS] + ["lr", "w"] + [f"val_{k}" for k in VAL_DIAGNOSTICS]


# Generated by Claude Code (Hard)
def history_row(tr, va):
    """One history.csv row. Epoch comes from the val dict so a resume keeps its numbering."""
    return [va["epoch"]] + [tr[k] for k in HISTORY_FIELDS] + [va[k] for k in HISTORY_FIELDS] + [va["lr"], va["w"]] + [va[k] for k in VAL_DIAGNOSTICS]


# Generated by Claude Code (Hard)
def format_epoch_breakdown(epoch, num_epochs, tr, va, epoch_seconds, w_trained):
    """Per-epoch table of every term, for stderr (stdout carries the CSV rows). gap = val - train, so a growing gap means memorising."""
    lines = [f"epoch {epoch + 1}/{num_epochs}  {epoch_seconds:.0f} s  lr {va['lr']:.2e}  w_trained {w_trained:.3f}",
             f"  {'term':<7} {'train':>10} {'val':>10} {'gap(val-train)':>15}"]
    for term in ("total", "L_pres", "L_MR", "L_gain", "L_abs"):
        train_value, val_value = tr[term], va[term]
        lines.append(f"  {term:<7} {train_value:>10.4f} {val_value:>10.4f} {val_value - train_value:>15.4f}")
    lines.append(f"  crops   train {tr['n_present']} present / {tr['n_absent']} absent   val {va['n_present']} / {va['n_absent']}")
    lines.append(f"  diag    enrol_sens {va['enrol_sens_db']:.2f} dB   pres_abs_gap {va['pres_abs_gap_db']:.2f} dB   content_wer {va['content_wer']:.2f} (smoothed {va['content_wer_ema']:.2f})")
    return "\n".join(lines)


def build_speaker_encoder(config, device):
    """Load the frozen ECAPA speaker encoder (Desplanques et al., 2020) for the extension, or return None for the baseline.

    Training and evaluation both build the encoder here, so they cannot embed a speaker differently.
    """
    if not config["model"].get("context_embedding", False):
        return None
    return load_context_encoder(device) # this loading comes from the context_encoder.py file to get the speaker embedding for the extension


def speaker_embedding(encoder, enrollment):
    """The enrolled speaker's embedding for the extension, or None for the baseline, which has no encoder."""
    if encoder is None:
        return None
    return embed_enrolment(encoder, enrollment) # this normalises the enrollment from the context and returns the speaker embedding for the extension

# see the ```diagnostic_report``` comment
def diagnostic_accumulate(diagnostics, model, mixture, enrollment, output, crop_absent, use_mixed_precision, enrol_embedding):
    """Add one validation batch to the running totals behind the two diagnostics.

    The enrolment swap pairs each mixture with the next clip's enrolment, so it needs a batch of at least two clips.
    """
    if mixture.shape[0] > 1:
        swapped_enrollment = enrollment.roll(1, 0)
        # The speaker embedding moves with its enrolment, otherwise only half of the speaker information would be swapped.
        swapped_embedding = None
        if enrol_embedding is not None:
            swapped_embedding = enrol_embedding.roll(1, 0)
        with mixed_precision(use_mixed_precision):
            swapped_output = extract(model, mixture, swapped_enrollment, enrol_embedding=swapped_embedding)
        # Back to float32, because sums of squares over 64,000 samples overflow in float16.
        swapped_output = swapped_output.float()
        diagnostics["swap_change_energy"] += float((output - swapped_output).pow(2).sum())
        diagnostics["output_energy"] += float(output.pow(2).sum())

    # Each crop's output energy relative to its own mixture, in dB.
    output_level_db = 10 * torch.log10(output.pow(2).sum(-1) / mixture.pow(2).sum(-1) + 1e-12)
    absent = crop_absent.bool()
    present = ~absent
    if present.any():
        diagnostics["present_level_db_sum"] += float(output_level_db[present].sum())
        diagnostics["present_crops"] += int(present.sum())
    if absent.any():
        diagnostics["absent_level_db_sum"] += float(output_level_db[absent].sum())
        diagnostics["absent_crops"] += int(absent.sum())


# This was suggested by Claude Code (Hard) where for each batch to see how much the change in enrollemnt sensitivity and presence gap has occured. This is to act as a diagnostic tool during training to give a better sense of whether the model is learning to focus more or less on the enrollment audio to learn the target.
def diagnostic_report(diagnostics):
    """Turn the running totals into the two logged numbers. Each one is NaN if its half of the data never appeared."""
    enrolment_sensitivity_db = float("nan")
    if diagnostics["output_energy"] > 0 and diagnostics["swap_change_energy"] > 0:
        enrolment_sensitivity_db = 10 * np.log10(diagnostics["swap_change_energy"] / diagnostics["output_energy"])
    presence_gap_db = float("nan")
    if diagnostics["present_crops"] and diagnostics["absent_crops"]:
        presence_gap_db = diagnostics["present_level_db_sum"] / diagnostics["present_crops"] - diagnostics["absent_level_db_sum"] / diagnostics["absent_crops"]
    return {"enrol_sens_db": enrolment_sensitivity_db, "pres_abs_gap_db": presence_gap_db}


def build_model(config):
    """Build the baseline from the config, or the extension when model.context_embedding is set."""
    # The extension (item 1c, decisions-m2.md 2026-09-22) adds a fusion for the 192-dimensional speaker embedding.
    if config["model"].get("context_embedding", False):
        embedding_dim = int(config["model"]["context_embedding_dim"])
    else:
        embedding_dim = None
    return build_bsrnn_tfmap(
        sample_rate=config["data"]["sample_rate"],
        n_fft=config["model"]["stft"]["n_fft"],
        hop=config["model"]["stft"]["hop"],
        feature_dim=config["model"]["separator"]["feature_dim"],
        hidden_dim=config["model"]["separator"]["lstm_hidden"],
        num_repeat=config["model"]["separator"]["num_repeat"],
        mlp_hidden=config["model"]["mask"]["mlp_hidden"],
        tfmap_scale=float(config["model"]["tfmap_scale"]),
        # Item 1a hands the cue over as its three parts, which adds 66,820 parameters.
        tfmap_parts=bool(config["model"].get("tfmap_parts", False)),
        tfmap_part_scales=config["model"].get("tfmap_part_scales"),
        embedding_dim=embedding_dim,
        # Frames each mask decision may hear ahead, 8 ms each. Absent in every trained model's config, so they build with 0 (decisions-pending.md 2026-10-29).
        lookahead_frames=int(config["model"].get("lookahead_frames", 0)),
    )


def mixed_precision(enabled):
    """Run the model's forward pass in float16 when enabled (Micikevicius et al., 2018).

    The loss stays in float32, because its 1e-12 safety terms vanish in float16.
    """
    if enabled:
        return torch.amp.autocast("cuda", dtype=torch.float16)
    return contextlib.nullcontext()

# this is to take one batch from the data loader and prepare it for the model.
def unpack(batch, device):
    """Move the mixture, target, enrolment and silence flags of one batch onto the device. The mixture is also the reference for the silence loss."""
    mixture = batch["mixture"].to(device)
    target = batch["target"].to(device)
    enrollment = batch["enrollment"].to(device)
    crop_absent = batch["crop_absent"].to(device)  # read from the cropped target audio, not the trial's label
    return mixture, target, enrollment, crop_absent

# accumulate loss terms
def add_parts(sums, counts, parts):
    """Accumulate each term weighted by the number of crops it was averaged over, so epoch means do not depend on the shuffle."""
    if parts["n_present"]:
        sums["L_pres"] += parts["L_pres"] * parts["n_present"]
        sums["L_MR"] += parts["L_MR"] * parts["n_present"]
        sums["L_gain"] += parts["L_gain"] * parts["n_present"]
        counts["present"] += parts["n_present"]
    if parts["n_absent"]:
        sums["L_abs"] += parts["L_abs"] * parts["n_absent"]
        counts["absent"] += parts["n_absent"]

# This was generated by Claude Code (Hard), and it is to report the epoch loss for each of the loss terms and the total loss for the epoch.
def epoch_report(sums, counts, absent_weight, multi_resolution_weight, gain_weight):
    """Turn the running sums into the epoch's mean loss terms.

    The total always uses the final absent weight, so every epoch is scored on the same objective (decisions-m2.md 2026-08-25).
    """
    nan = float("nan")
    n_present, n_absent = counts["present"], counts["absent"]
    L_pres = sums["L_pres"] / n_present if n_present else nan
    L_MR = sums["L_MR"] / n_present if n_present else nan
    L_gain = sums["L_gain"] / n_present if n_present else nan
    L_abs = sums["L_abs"] / n_absent if n_absent else nan
    return {
        "total": (1 - absent_weight) * (L_pres + multi_resolution_weight * L_MR + gain_weight * L_gain) + absent_weight * L_abs,
        "L_pres": L_pres,
        "L_MR": L_MR,
        "L_gain": L_gain,
        "L_abs": L_abs,
        "n_present": n_present,
        "n_absent": n_absent,
    }


# the next 2 methods are used to choose which epoch to keep, and the same score decides when to lower the learning rate. Code was editted and refined by Claude
# --------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------------- #
def selection_score(val_loss):
    """The number that decides which epoch to keep and when to lower the learning rate. Lower is better.

    It is the smoothed validation WER, the only score that tracks content (decisions-m2.md 2026-09-23). It is smoothed because the WER of one epoch is too noisy to step a scheduler on.
    """
    return float(val_loss["content_wer_ema"])


def selection_eligible(val_loss, config):
    """Whether an epoch may be kept at all: its silence loss L_abs must be at or below training.select_abs_max."""
    return float(val_loss["L_abs"]) <= float(config["training"]["select_abs_max"])
