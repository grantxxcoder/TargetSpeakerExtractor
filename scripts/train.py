def log_results(out_dir, config, config_path, args, model, device, manifest_csv, train_loss_history, val_loss_history, best_row, wall_s, num_epochs, save_path):
    """Write experiments/results/<dir>/{meta.yaml, history.csv}: config, metrics, seed and date (CLAUDE.md). Never raises."""
    try:
        out_dir = Path(out_dir)
        out_dir.mkdir(parents=True, exist_ok=True)

        with open(out_dir / "history.csv", "w", newline="") as f:
            writer = csv.writer(f, lineterminator="\n")  # LF, matching the rows printed to stdout
            writer.writerow(history_header())
            for tr, va in zip(train_loss_history, val_loss_history):
                writer.writerow(history_row(tr, va))

        manifest_meta = yaml.safe_load(Path(manifest_csv).with_suffix(".meta.yaml").read_text())
        epochs_run = len(train_loss_history)
        last_epoch = val_loss_history[-1]["epoch"] if val_loss_history else -1

        (out_dir / "meta.yaml").write_text(yaml.safe_dump({
            "date": date.today().isoformat(),
            "script": "scripts/train.py",
            "seed": int(config["seed"]),
            "config": str(config_path),
            "config_md5": hashlib.md5(Path(config_path).read_bytes()).hexdigest(),
            "manifest": str(manifest_csv),
            "manifest_config_md5": manifest_meta.get("config_md5"),
            "device": str(device),
            "resumed": bool(args.resume),
            "model": {
                "system": "extension" if hasattr(model, "context") else "baseline",
                "n_parameters": sum(p.numel() for p in model.parameters()),
                "n_bands": len(model.band_widths),
            },
            "epochs_requested": num_epochs,
            "epochs_run": epochs_run,
            "early_stopped": bool(epochs_run and last_epoch + 1 < num_epochs),
            "wall_seconds": round(wall_s, 1),
            "seconds_per_epoch": round(wall_s / epochs_run, 1) if epochs_run else None,
            # Copied so the result is readable without the yaml.
            "data": config["data"],
            "loss": config["loss"],
            "training": config["training"],
            "best_val": {k: (best_row or {}).get(k) for k in ["epoch", "total", "L_pres", "L_MR", "L_abs", "content_wer_ema", "lr"]},
            "final_train": train_loss_history[-1] if train_loss_history else {},
            "checkpoint": str(save_path),
        }, sort_keys=False))

        print(f"Wrote {out_dir}/meta.yaml and {out_dir}/history.csv")
        return True
    except Exception as e:  # A logging bug must not discard a finished run.
        print(f"  log_results: could not write {out_dir}: {e}", file=sys.stderr)
        return False

# this is where I start the training script
def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="experiments/configs/bsrnn_cue_context.yaml")
    parser.add_argument("--epochs", type=int, default=None, help="stop after this epoch instead of training.epochs, so one run can be split across sessions with --resume")
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--outdir", default="models/")
    parser.add_argument("--data-root", default="data")
    parser.add_argument("--manifest-dir", default="data/manifests")
    args = parser.parse_args()

    config_path = Path(args.config)
    config = yaml.safe_load(config_path.read_text())
    data_root = Path(args.data_root)
    manifest_dir = Path(args.manifest_dir)

    # Seed every run, before the model is built so the weight init is reproducible too.
    seed = int(config["seed"])
    torch.manual_seed(seed)
    np.random.seed(seed)
    num_epochs = args.epochs if args.epochs is not None else int(config["training"]["epochs"])
    print(f"seed {seed}  epochs {num_epochs}  config {config_path}")

    train_loader, val_loader = get_data_loaders(manifest_dir, data_root, config)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = build_model(config)
    # A fine-tune starts from a trained model's weights, named by training.init_weights. A resume reads its own checkpoint below instead.
    init_weights = config["training"].get("init_weights")
    if init_weights and not args.resume:
        start_checkpoint = torch.load(init_weights, map_location="cpu", weights_only=False)  # our own file: it carries the config dict
        model.load_state_dict(start_checkpoint["model"])
        print(f"started from {init_weights} (epoch {start_checkpoint.get('epoch')}), md5 {hashlib.md5(Path(init_weights).read_bytes()).hexdigest()}")
    model.to(device)

    # Item 1c's encoder lives beside the model: frozen, not optimised, not saved in checkpoints.
    speaker_encoder = build_speaker_encoder(config, device)
    content_probe = build_content_probe(config, data_root, manifest_dir)

    optimizer = torch.optim.AdamW(model.parameters(), lr=float(config["training"]["lr"]), weight_decay=float(config["training"]["weight_decay"]))  # AdamW (Loshchilov & Hutter, 2019)
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(optimizer, mode="min", factor=float(config["training"]["lr_factor"]), patience=int(config["training"]["lr_patience"]))

    save_path = Path(args.outdir) / "model_sir0.pt"
    save_path.parent.mkdir(parents=True, exist_ok=True)

    start_epoch = 0
    start_step = 0
    best_val = float("inf")
    best_row = None

    if args.resume:
        checkpoint = torch.load(save_path, map_location=device, weights_only=False)  # our own file: it carries the config dict
        if checkpoint["config"] != config:
            raise ValueError(f"{save_path} was trained under a different config, start a fresh run or pass a matching --config")
        model.load_state_dict(checkpoint["model"])
        optimizer.load_state_dict(checkpoint["optimizer"])
        scheduler.load_state_dict(checkpoint["scheduler"])
        start_epoch = checkpoint["epoch"] + 1
        start_step = int(checkpoint["global_step"])
        best_val = checkpoint["best_val"]
        best_row = checkpoint["best_row"]
        # The probe's smoothing carries on from where the checkpoint left it.
        probe_warm_start(content_probe, checkpoint["content_wer_history"])
        print(f"resumed {save_path} at epoch {start_epoch}, step {start_step}, best_val {best_val:.4f}")

    # `timed` writes the docs/run_times.md row, marked (failed) if training dies.
    progress = {"epochs": 0}
    start_time = time.time()
    with timed(f"scripts/train.py --config {config_path}", scope=lambda: f"{len(train_loader.dataset):,} trials x {progress['epochs']} epochs, sir0", rate=lambda: f"batch {config['data']['batch_size']}, {device}, {(time.time() - start_time) / max(progress['epochs'], 1):.0f} s/epoch"):
        train_loss_history, val_loss_history, best_row = train(model, train_loader, val_loader, optimizer, scheduler, num_epochs, device, save_path, config, content_probe, speaker_encoder, start_epoch, best_val, best_row, start_step)
        progress["epochs"] = len(train_loss_history)
    wall_seconds = time.time() - start_time

    results_dir = Path("experiments/results") / f"{date.today().isoformat()}-train-sir0"
    log_results(results_dir, config, config_path, args, model, device, manifest_dir / f"{TRAIN_SPLIT}.csv", train_loss_history, val_loss_history, best_row, wall_seconds, num_epochs, save_path)


if __name__ == "__main__":
    main()
