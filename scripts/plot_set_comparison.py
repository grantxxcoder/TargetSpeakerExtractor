"""Draws the report's three-set comparison: Gemini's word error rate for every system on the validation, test and AMI sets, with 95 % intervals.

    ../tse_venv/bin/python scripts/plot_set_comparison.py --out report/figures/set_comparison.pdf

One panel per set, all on the same axis, so a reader can see both whether the ranking of the systems holds and how much harder real recordings are.
Validation (sir0_val, 103 two-speaker trials) points are the mean of three judge runs with intervals that redraw whole speakers (experiments/results/2026-10-07-ci-clustered).
Test (eval_private, 248 two-speaker trials) points are one judge run with intervals that redraw whole target speakers (experiments/results/2026-10-27-test-set-paired-ci/ci.json). The matched baseline was judged on 2026-10-27 and the other systems on 2026-10-08.
AMI (300 real meeting stretches) points are one run with intervals that redraw whole meetings (experiments/results/2026-10-12-ami-ft-final/paired_ci.json).
The matched baseline was never scored on the AMI set, so that row says so instead of showing a point.
On AMI the reference point is the target's own headset, which also picks up the other speaker, so it is not a clean target.
Judge: gemini-3.7-flash, AI Studio, audio in and text out, prompt d118b7d3bf30.
Claude Code wrote this script from the author's figure specification (2026-10-27).
"""

import argparse
import json
from pathlib import Path

import matplotlib as mpl
import matplotlib.pyplot as plt

# The figure is written straight to a file, without a screen.
mpl.use("Agg")

# House style for every report figure, copied from scripts/plot_training_curves.py. Generated by Claude Code
mpl.rcParams.update({
    "font.family": "serif",
    "font.serif": ["Times New Roman", "Nimbus Roman", "DejaVu Serif"],
    "font.size": 9, "axes.labelsize": 9, "axes.titlesize": 9,
    "xtick.labelsize": 8, "ytick.labelsize": 8, "legend.fontsize": 8,
    "axes.linewidth": 0.6, "xtick.major.width": 0.6, "ytick.major.width": 0.6,
    "axes.spines.top": False, "axes.spines.right": False,
    "figure.dpi": 140, "savefig.dpi": 300,
    "savefig.bbox": "tight", "savefig.pad_inches": 0.01, "pdf.fonttype": 42,
    "mathtext.fontset": "stix",
})
TEXTWIDTH_IN = 6.3
FIGURE_HEIGHT_IN = 1.9
INK = "#222222"
BLUE = "#0B6E99"
ORANGE = "#C1440E"
MUTED = "#6B6B6B"

RESULTS = Path(__file__).resolve().parents[1] / "experiments/results"
VALIDATION_DIRECTORY = RESULTS / "2026-10-07-ci-clustered"
TEST_FILE = RESULTS / "2026-10-27-test-set-paired-ci/ci.json"
AMI_FILE = RESULTS / "2026-10-12-ami-ft-final/paired_ci.json"

# The rows from top to bottom, with each system's colour and marker. Models are diamonds and the two reference points are squares, as in the leak-versus-invention map.
ROWS = [
    ("No processing", MUTED, "s"),
    ("Baseline", ORANGE, "D"),
    ("Extension", BLUE, "D"),
    ("WeSep", INK, "D"),
    ("Target alone", MUTED, "s"),
]

# The file and key that hold each system's validation interval.
VALIDATION_FILES = {
    "No processing": "no_processing.json",
    "Baseline": "baseline.json",
    "Extension": "extension.json",
    "WeSep": "wesep.json",
    "Target alone": "target_alone.json",
}

# The names each file uses for each system. The baseline is absent from the AMI file.
TEST_NAMES = {"No processing": "No processing", "Baseline": "Baseline", "Extension": "Extension", "WeSep": "WeSep", "Target alone": "Target alone"}
AMI_NAMES = {"No processing": "No processing", "Extension": "e21", "WeSep": "WeSep", "Target alone": "Target's headset"}

X_LIMIT = 140.0


# this reads the validation word error rate and its interval for every system
def read_validation():
    points = {}
    for system, file_name in VALIDATION_FILES.items():
        with open(VALIDATION_DIRECTORY / file_name) as handle:
            scores = json.load(handle)
        points[system] = (scores["lcf_wer_3run_mean"], scores["ci95_speaker_clustered"][0], scores["ci95_speaker_clustered"][1])
    return points


# this reads the test word error rate and interval of every system, all scored on the same resampled speakers
def read_test():
    with open(TEST_FILE) as handle:
        scored_systems = json.load(handle)["systems"]
    points = {}
    for system, stored_name in TEST_NAMES.items():
        scores = scored_systems[stored_name]
        points[system] = (scores["lcf_wer"], scores["ci95"][0], scores["ci95"][1])
    return points


# this reads the word error rate and interval of every system that was scored on one of the paired_ci.json sets
def read_paired_set(set_name, system_names):
    with open(AMI_FILE) as handle:
        scored_systems = json.load(handle)["sets"][set_name]["systems"]
    points = {}
    for system, stored_name in system_names.items():
        scores = scored_systems[stored_name]
        points[system] = (scores["lcf_wer"], scores["ci95"][0], scores["ci95"][1])
    return points


# this draws one panel: a row per system, the point with its interval, and its value written beside it
def draw_panel(axis, points, title, reference_note):
    for row_number, (system, colour, marker) in enumerate(ROWS):
        if system not in points:
            axis.text(2.0, row_number, "not scored", fontsize=8, color=MUTED, va="center", ha="left")
            continue
        value, low, high = points[system]
        axis.plot([low, high], [row_number, row_number], color=colour, linewidth=0.9, solid_capstyle="butt", zorder=2)
        axis.scatter(value, row_number, s=26, marker=marker, facecolor=colour, edgecolor=colour, zorder=3)
        label = f"{value:.1f}"
        if system == "Target alone" and reference_note:
            label = f"{value:.1f} ({reference_note})"
        axis.annotate(label, (max(high, value), row_number), xytext=(7, 0), textcoords="offset points", fontsize=8, color=INK, va="center", ha="left")
    axis.set_xlim(0, X_LIMIT)
    axis.set_ylim(len(ROWS) - 0.5, -0.5)
    axis.set_xlabel("LCF-WER (%)")
    axis.set_title(title, loc="left")
    axis.tick_params(axis="y", length=0)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default="report/figures/set_comparison.pdf")
    arguments = parser.parse_args()

    validation = read_validation()
    test = read_test()
    ami = read_paired_set("ami_eval", AMI_NAMES)

    figure, axes = plt.subplots(1, 3, figsize=(TEXTWIDTH_IN, FIGURE_HEIGHT_IN), sharey=True, gridspec_kw={"wspace": 0.12})
    draw_panel(axes[0], validation, "(a) Validation, 103 trials", None)
    draw_panel(axes[1], test, "(b) Test, 248 trials", None)
    draw_panel(axes[2], ami, "(c) AMI, 300 trials", "headset")
    row_labels = []
    for system, colour, marker in ROWS:
        row_labels.append(system)
    axes[0].set_yticks(range(len(ROWS)))
    axes[0].set_yticklabels(row_labels)

    output_path = Path(arguments.out)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(output_path)
    print(f"wrote {output_path}")
    # Print the plotted values so they can be checked against the results tables. Generated by Claude Code
    for set_name, points in (("validation", validation), ("test", test), ("AMI", ami)):
        for system, (value, low, high) in points.items():
            print(f"{set_name:10s} {system:14s} {value:7.2f}  [{low:7.2f}, {high:7.2f}]")


if __name__ == "__main__":
    main()
