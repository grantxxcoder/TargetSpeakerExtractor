"""Draws the report's conventional-measures figure: SDR, SIR, SAR and the four DNSMOS scores for every system, side by side.

    ../tse_venv/bin/python scripts/plot_conventional_measures.py --out report/figures/conventional_measures.pdf

One panel per kind of measure, stacked at full text width, with one group of five bars per metric (no processing, baseline, extension, WeSep, target alone), so a reader can compare each measure's ranking of the systems with Gemini's (the table beside it in results.tex).
The bars are wide enough for each value to be written level above its bar.
A signal value at the +30 dB cap of the denominator floor is not a measurement, so its bar is left out: no processing's SAR and all three of the target alone's signal values.
All values are on sir0_val, the 103 two-speaker validation trials, speech gate on.
No processing, extension and target alone come from experiments/results/2026-09-26-eval-cuecontext-wer-e21-signal, the matched baseline e11 from 2026-10-09-eval-baseline-matched-e11-signal-perceptual, and WeSep from 2026-10-28-eval-wesep-signal-perceptual (recomputed because the report's WeSep row had no results file on disk; it matched the row exactly).
Claude Code wrote this script from the author's figure specification (2026-10-28).
"""

import argparse
import json
from pathlib import Path

import matplotlib as mpl
import matplotlib.pyplot as plt
from matplotlib.patches import Patch

# The figure is written straight to a file, without a screen.
mpl.use("Agg")

# House style for every report figure, copied from scripts/plot_training_curves.py. Generated by Claude Code
mpl.rcParams.update({
    "font.family": "serif",
    "font.serif": ["Times New Roman", "Nimbus Roman", "DejaVu Serif"],
    "font.size": 9, "axes.labelsize": 9, "axes.titlesize": 9,
    "xtick.labelsize": 8, "ytick.labelsize": 8, "legend.fontsize": 8,
    "axes.linewidth": 0.6, "xtick.major.width": 0.6, "ytick.major.width": 0.6,
    "axes.spines.top": False, "axes.spines.right": False,
    "figure.dpi": 140, "savefig.dpi": 300,
    "savefig.bbox": "tight", "savefig.pad_inches": 0.01, "pdf.fonttype": 42,
    "mathtext.fontset": "stix",
})
TEXTWIDTH_IN = 6.3
FIGURE_HEIGHT_IN = 3.5
INK = "#222222"
BLUE = "#0B6E99"
ORANGE = "#C1440E"
MUTED = "#6B6B6B"
LIGHT_GREY = "#C8C8C8"
# WeSep gets its own colour, not ink, so the black error bars stay visible on its bars; reddish purple from the colour-blind-safe palette of Okabe and Ito (2008).
WESEP_COLOUR = "#CC79A7"

RESULTS = Path(__file__).resolve().parents[1] / "experiments/results"
SIGNAL_E21 = RESULTS / "2026-09-26-eval-cuecontext-wer-e21-signal/results.json"

# The file and the system name inside it that hold each system's signal and DNSMOS scores.
SOURCES = {
    "No processing": (SIGNAL_E21, "floor"),
    "Baseline": (RESULTS / "2026-10-09-eval-baseline-matched-e11-signal-perceptual/results.json", "estimate"),
    "Extension": (SIGNAL_E21, "estimate"),
    "WeSep": (RESULTS / "2026-10-28-eval-wesep-signal-perceptual/results.json", "estimate"),
    "Target alone": (SIGNAL_E21, "ceiling"),
}

# The five systems drawn as bars in each group, with the colours of the other results figures; the two reference points are grey.
BARS = [("No processing", MUTED), ("Baseline", ORANGE), ("Extension", BLUE), ("WeSep", WESEP_COLOUR), ("Target alone", LIGHT_GREY)]

# Each panel: its title, its metrics as (key, label), the value the bars start from, the y-axis range and the number format of the bar labels. Higher is better for every metric.
PANELS = [
    ("Signal (dB)", [("sdr", "SDR"), ("sir", "SIR"), ("sar", "SAR")], 0.0, (-3.0, 12.5), "{:.2f}"),
    ("DNSMOS (1 to 5)", [("p808", "P.808"), ("sig", "SIG"), ("bak", "BAK"), ("ovrl", "OVRL")], 1.0, (1.0, 4.7), "{:.2f}"),
]

# The signal measures are capped at +30 dB by the denominator floor, so a value at the cap is not a measurement and gets no bar.
CAP_DB = 30.0
BAR_WIDTH = 0.18


# this reads every system's signal and DNSMOS scores from its results.json file
def read_all():
    values = {}
    for name, (path, system) in SOURCES.items():
        with open(path) as handle:
            results = json.load(handle)
        values[name] = results["systems"][system]
    return values


# this draws one panel: a group of five bars per metric, one per system, each with its value written above it (below it when negative)
def draw_panel(axis, values, title, metrics, bottom, y_range, number_format):
    tick_labels = []
    pad = 0.015 * (y_range[1] - y_range[0])
    for position, (key, label) in enumerate(metrics):
        for index, (name, colour) in enumerate(BARS):
            value = values[name][key]
            if key in ("sdr", "sir", "sar") and value >= CAP_DB:
                continue
            x = position + (index - 2) * BAR_WIDTH
            axis.bar(x, value - bottom, bottom=bottom, width=BAR_WIDTH * 0.9, color=colour, linewidth=0)
            # A true minus sign, not a hyphen, as in the report's tables.
            text = number_format.format(value).replace("-", "−")
            if value >= bottom:
                axis.text(x, value + pad, text, fontsize=7.5, color=INK, ha="center", va="bottom")
            else:
                axis.text(x, value - pad, text, fontsize=7.5, color=INK, ha="center", va="top")
        tick_labels.append(label + r" $\uparrow$")
    axis.set_xticks(range(len(metrics)))
    axis.set_xticklabels(tick_labels)
    axis.tick_params(axis="x", length=0)
    axis.set_xlim(-0.5, len(metrics) - 0.5)
    axis.set_ylim(*y_range)
    if bottom == 0.0 and y_range[0] < 0:
        axis.axhline(0.0, color=INK, linewidth=0.6)
    axis.set_title(title, fontsize=9)


# this draws the two panels one above the other, with one legend above them
def draw(output_path):
    values = read_all()
    # The side margins are kept small, so the panels fill the text width once the tight bounding box trims the figure.
    figure, axes = plt.subplots(len(PANELS), 1, figsize=(TEXTWIDTH_IN, FIGURE_HEIGHT_IN), gridspec_kw={"hspace": 0.45, "left": 0.06, "right": 0.99, "top": 0.86})
    for axis, (title, metrics, bottom, y_range, number_format) in zip(axes, PANELS):
        draw_panel(axis, values, title, metrics, bottom, y_range, number_format)
    handles = []
    for name, colour in BARS:
        legend_name = name
        if name == "Target alone":
            legend_name = "Target alone (perfect)"
        handles.append(Patch(facecolor=colour, label=legend_name))
    figure.legend(handles=handles, loc="lower center", bbox_to_anchor=(0.5, 0.9), ncol=5, frameon=False, handlelength=1.2, columnspacing=1.4)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(output_path)
    # Generated by Claude Code
    print(f"wrote {output_path}")
    for name, scores in values.items():
        print(f"  {name:<14} sdr {scores['sdr']:+6.2f}  sir {scores['sir']:+6.2f}  sar {scores['sar']:+6.2f}  p808 {scores['p808']:.2f}  sig {scores['sig']:.2f}  bak {scores['bak']:.2f}  ovrl {scores['ovrl']:.2f}")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default="report/figures/conventional_measures.pdf")
    arguments = parser.parse_args()
    draw(Path(arguments.out))


if __name__ == "__main__":
    main()
