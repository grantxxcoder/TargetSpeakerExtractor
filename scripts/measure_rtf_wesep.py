"""Real-time factor and end-to-end latency of the borrowed WeSep checkpoint. Run it under the WeSep virtualenv, where wesep is installed:

    ../wesep_venv/bin/python scripts/measure_rtf_wesep.py --pretrain ../wesep_pretrained/tfmap_context_causal_100

The protocol is copied from scripts/measure_rtf.py term for term, so the two rows of the latency table measure the same thing: CPU, 4 threads, 80 ms chunks, 60 s of audio three times. Change one and change both.
Borrowed model: Wang et al., Interspeech 2024, "WeSep: A Scalable and Flexible Toolkit Towards Generalizable Target Speaker Extraction". No number from this script is comparable to a published REAL-TSE latency figure.
The lookahead is read from WeSep's own config and converted with our convention, window fill plus emit hop, the same one stft_latency_ms uses. At 512 / 128 and 16 kHz that is 40 ms, the same as our model.
Each chunk goes through extract_speech_from_pcm on its own, the configuration that produced WeSep's scores, so the enrolment is re-embedded every chunk, just as our model rebuilds its cue every chunk. The audio is thrown away, and the figure is an estimate with 10 to 20 % error.
A good RTF here does not show that WeSep can stream: causality decides that, and it is reported separately.
"""

import argparse
import json
import statistics
import sys
import time
from datetime import date
from pathlib import Path

import torch
import wesep
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from src.run_log import timed

# The same protocol as measure_rtf.py. Keep them in step.
CHUNK_MS = 80.0
THREADS = 4
AUDIO_SECONDS = 60.0
REPEATS = 3
ENROLLMENT_SECONDS = 5.0
WARMUP_CHUNKS = 20
SAMPLE_RATE = 16000


# this reads the CPU's model name, which an RTF figure is meaningless without
def hardware_description():
    for line in Path("/proc/cpuinfo").read_text().splitlines():
        if line.startswith("model name"):
            return line.split(":", 1)[1].strip()
    return "unknown"


# this reads WeSep's framing from its own config, so the lookahead and its declared causality travel with the timing
def describe_checkpoint(pretrain_dir):
    config = yaml.safe_load(open(Path(pretrain_dir) / "config.yaml"))
    separator = config.get("model_args", {}).get("tse_model", {}).get("separator", {})
    return {"win": int(separator.get("win", 0)), "stride": int(separator.get("stride", 0)), "causal_declared": bool(separator.get("causal", False)), "config_resample_rate": int(config.get("dataset_args", {}).get("resample_rate", 16000))}


# this loads WeSep exactly as make_estimates_wesep.py does, with its own VAD and output normalisation off
def build_model(pretrain_dir):
    model = wesep.load_model_local(str(pretrain_dir))
    model.set_resample_rate(SAMPLE_RATE)
    model.set_vad(False)
    model.set_device("cpu")
    model.set_output_norm(False)
    return model


# this is where the measurement starts
def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--pretrain", required=True, help="a WeSep checkpoint folder holding avg_model.pt and config.yaml")
    parser.add_argument("--out", default=None)
    args = parser.parse_args()

    torch.set_num_threads(THREADS)
    facts = describe_checkpoint(args.pretrain)
    if facts["config_resample_rate"] != SAMPLE_RATE:
        raise SystemExit(f"The checkpoint was trained at {facts['config_resample_rate']} Hz, and resampling inside the timed loop would be measured as model cost.")
    model = build_model(args.pretrain)
    lookahead_ms = 1000.0 * (facts["win"] + facts["stride"]) / SAMPLE_RATE

    chunk_samples = int(round(CHUNK_MS / 1000.0 * SAMPLE_RATE))
    enrollment = torch.randn(1, int(ENROLLMENT_SECONDS * SAMPLE_RATE))
    chunk = torch.randn(1, chunk_samples)
    # This counts the TSE model as instantiated. The state-dict total in make_estimates_wesep.py (33.46 M) also counts entries not live in the forward pass.
    parameter_count = 0
    for parameter in model.model.parameters():
        parameter_count += parameter.numel()

    # Generated by Claude Code
    print(f"  checkpoint        {args.pretrain}")
    print(f"  device            cpu  ({hardware_description()})")
    print(f"  threads           {THREADS}")
    print(f"  chunk             {CHUNK_MS:.0f} ms = {chunk_samples} samples")
    print(f"  model lookahead   {lookahead_ms:.1f} ms  (win {facts['win']} + stride {facts['stride']} @ {SAMPLE_RATE} Hz, our convention)")
    print(f"  declared causal   {facts['causal_declared']}")
    print(f"  parameters timed  {parameter_count:,}  (state-dict total is 33.46 M)")

    for warmup_index in range(WARMUP_CHUNKS):
        model.extract_speech_from_pcm(chunk, SAMPLE_RATE, enrollment, SAMPLE_RATE)
    chunks_per_repeat = int(AUDIO_SECONDS * 1000 / CHUNK_MS)
    per_chunk_ms = []
    for repeat_index in range(REPEATS):
        for chunk_index in range(chunks_per_repeat):
            start = time.perf_counter()
            model.extract_speech_from_pcm(chunk, SAMPLE_RATE, enrollment, SAMPLE_RATE)
            per_chunk_ms.append((time.perf_counter() - start) * 1000.0)
    per_chunk_ms.sort()

    def percentile(p):
        return per_chunk_ms[min(int(p / 100 * len(per_chunk_ms)), len(per_chunk_ms) - 1)]

    mean_ms = statistics.fmean(per_chunk_ms)
    result = {
        "date": date.today().isoformat(),
        "system": "wesep-borrowed",
        "checkpoint": str(args.pretrain),
        "parameters_timed": parameter_count,
        "declared_causal": facts["causal_declared"],
        "win": facts["win"],
        "stride": facts["stride"],
        "enrollment_mode": "reembed_per_chunk",
        "wesep_vad": False,
        "wesep_output_norm": False,
        "device": "cpu",
        "hardware": hardware_description(),
        "threads": THREADS,
        "chunk_ms": CHUNK_MS,
        "chunks_timed": len(per_chunk_ms),
        "lookahead_ms": lookahead_ms,
        "lookahead_convention": "window fill + emit hop (src/models/stft.py)",
        "per_chunk_mean_ms": mean_ms,
        "per_chunk_p50_ms": percentile(50),
        "per_chunk_p95_ms": percentile(95),
        "per_chunk_p99_ms": percentile(99),
        "per_chunk_max_ms": per_chunk_ms[-1],
        "rtf_mean": mean_ms / CHUNK_MS,
        "rtf_p99": percentile(99) / CHUNK_MS,
        "latency_mean_ms": CHUNK_MS + lookahead_ms + mean_ms,
        "latency_p99_ms": CHUNK_MS + lookahead_ms + percentile(99),
        "keeps_up": bool(percentile(99) < CHUNK_MS),
        "note": "ESTIMATE: chunks processed independently, no state carried. Output discarded. 10-20 % error. Not a streaming measurement. Says nothing about whether WeSep is causal.",
        "not_comparable_to": "any published REAL-TSE latency figure",
    }

    # Generated by Claude Code
    print(f"\n  per chunk   mean {mean_ms:7.2f} ms   p50 {percentile(50):7.2f}   p95 {percentile(95):7.2f}   p99 {percentile(99):7.2f}   max {per_chunk_ms[-1]:7.2f}")
    print(f"  chunks timed      {len(per_chunk_ms)}")
    print()
    print(f"  RTF mean          {result['rtf_mean']:.4f}   ({'keeps up' if result['rtf_mean'] < 1 else 'FALLS BEHIND'}, needs < 1)")
    print(f"  RTF p99           {result['rtf_p99']:.4f}   ({'no chunk misses the deadline' if result['keeps_up'] else 'SOME CHUNKS MISS THE DEADLINE'})")
    print(f"  latency mean      {result['latency_mean_ms']:.1f} ms   = {CHUNK_MS:.0f} chunk + {lookahead_ms:.0f} lookahead + {mean_ms:.1f} compute")
    print(f"  latency p99       {result['latency_p99_ms']:.1f} ms   (budget 200-300 ms)")

    out_dir = Path(args.out or f"experiments/results/{date.today().isoformat()}-rtf-wesep-cpu")
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "rtf.json").write_text(json.dumps(result, indent=2))
    print(f"\n  written to {out_dir}/rtf.json")


# this gives the scope line for the run-times log: the command line as typed
def run_scope():
    return " ".join(sys.argv[1:])


if __name__ == "__main__":
    with timed("scripts/measure_rtf_wesep.py", run_scope):
        main()
