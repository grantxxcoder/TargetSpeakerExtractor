"""Measure the real-time factor and end-to-end latency of the extractor, on the CPU with 4 threads and 80 ms chunks.

    python scripts/measure_rtf.py --checkpoint models/model_sir0_cuecontext-wer-e21.pt

Both numbers come from the time taken to process one chunk. RTF is processing time over audio duration and must be below 1, or the backlog grows forever.
Latency is the chunk plus the STFT's lookahead plus the processing time, and must fit the 200 to 300 ms budget (decisions-m0.md 2026-08-07). With RTF below 1 the budget is met automatically.
It times chunks rather than whole clips, because a whole-clip LSTM call is one batched multiply and flatters streaming by up to 32 times (measured 2026-09-01).
80 ms chunks capture most of the available efficiency and keep the end-to-end delay at 120 ms plus processing.
Each chunk goes through extract() on its own, so the audio is wrong and thrown away, but the timing is close, because carrying a hidden state costs the same as starting a fresh one. Treat it as an estimate with 10 to 20 % error.
"""

import argparse
import json
import statistics
import sys
import time
from datetime import date
from pathlib import Path

import torch

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src.models.bsrnn import extract
from src.models.stft import stft_latency_ms
from src.run_log import timed
from train import build_model, build_speaker_encoder, speaker_embedding

CHUNK_MS = 80.0
THREADS = 4
AUDIO_SECONDS = 60.0
REPEATS = 3
ENROLLMENT_SECONDS = 5.0
WARMUP_CHUNKS = 20


# this reads the CPU's model name, which an RTF figure is meaningless without
def hardware_description():
    for line in Path("/proc/cpuinfo").read_text().splitlines():
        if line.startswith("model name"):
            return line.split(":", 1)[1].strip()
    return "unknown"


# this is where the measurement starts
def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--checkpoint", default="models/model_sir0_cuecontext-wer-e21.pt")
    parser.add_argument("--out", default=None)
    args = parser.parse_args()

    torch.set_num_threads(THREADS)
    device = torch.device("cpu")
    checkpoint = torch.load(args.checkpoint, map_location="cpu", weights_only=False)
    model = build_model(checkpoint["config"])
    model.load_state_dict(checkpoint["model"])
    model.eval().to(device)
    sample_rate = int(checkpoint["config"]["data"]["sample_rate"])
    # The framing's delay, plus one hop for each frame the mask waits to hear ahead (lookahead_frames, decisions-pending.md 2026-10-29). Zero frames for every model before the lookahead fine-tune.
    lookahead_ms = stft_latency_ms(model.stft) + 1000 * model.lookahead_frames * model.stft.hop_length / model.stft.sample_rate

    chunk_samples = int(round(CHUNK_MS / 1000.0 * sample_rate))
    enrollment = torch.randn(1, int(ENROLLMENT_SECONDS * sample_rate), device=device)
    chunk = torch.randn(1, chunk_samples, device=device)

    # The speaker embedding is computed once, outside the timing loop, because the enrolment is known before the stream starts. That placement is the claim: the encoder adds nothing per frame.
    encoder = build_speaker_encoder(checkpoint["config"], device)
    enrol_embedding = speaker_embedding(encoder, enrollment)

    parameter_count = 0
    for parameter in model.parameters():
        parameter_count += parameter.numel()
    # Generated by Claude Code
    print(f"  device            cpu  ({hardware_description()})")
    print(f"  threads           {THREADS}")
    print(f"  chunk             {CHUNK_MS:.0f} ms = {chunk_samples} samples")
    print(f"  model lookahead   {lookahead_ms:.1f} ms")
    print(f"  parameters        {parameter_count:,}")

    per_chunk_ms = []
    with torch.inference_mode():
        for warmup_index in range(WARMUP_CHUNKS):
            extract(model, chunk, enrollment, enrol_embedding=enrol_embedding)
        chunks_per_repeat = int(AUDIO_SECONDS * 1000 / CHUNK_MS)
        for repeat_index in range(REPEATS):
            for chunk_index in range(chunks_per_repeat):
                start = time.perf_counter()
                extract(model, chunk, enrollment, enrol_embedding=enrol_embedding)
                per_chunk_ms.append((time.perf_counter() - start) * 1000.0)
    per_chunk_ms.sort()

    def percentile(p):
        return per_chunk_ms[min(int(p / 100 * len(per_chunk_ms)), len(per_chunk_ms) - 1)]

    mean_ms = statistics.fmean(per_chunk_ms)
    result = {
        "date": date.today().isoformat(),
        "checkpoint": args.checkpoint,
        "device": "cpu",
        "hardware": hardware_description(),
        "threads": THREADS,
        "chunk_ms": CHUNK_MS,
        "chunks_timed": len(per_chunk_ms),
        "lookahead_ms": lookahead_ms,
        "lookahead_frames": model.lookahead_frames,
        "per_chunk_mean_ms": mean_ms,
        "per_chunk_p50_ms": percentile(50),
        "per_chunk_p95_ms": percentile(95),
        "per_chunk_p99_ms": percentile(99),
        "per_chunk_max_ms": per_chunk_ms[-1],
        "rtf_mean": mean_ms / CHUNK_MS,
        "rtf_p99": percentile(99) / CHUNK_MS,
        "latency_mean_ms": CHUNK_MS + lookahead_ms + mean_ms,
        "latency_p99_ms": CHUNK_MS + lookahead_ms + percentile(99),
        "keeps_up": bool(percentile(99) < CHUNK_MS),
        "note": "ESTIMATE: chunks processed independently, no state carried. Output discarded. 10-20 % error. Not a streaming measurement.",
    }

    # Generated by Claude Code
    print(f"\n  per chunk   mean {mean_ms:7.2f} ms   p50 {percentile(50):7.2f}   p95 {percentile(95):7.2f}   p99 {percentile(99):7.2f}   max {per_chunk_ms[-1]:7.2f}")
    print(f"  chunks timed      {len(per_chunk_ms)}")
    print()
    print(f"  RTF mean          {result['rtf_mean']:.4f}   ({'keeps up' if result['rtf_mean'] < 1 else 'FALLS BEHIND'}, needs < 1)")
    print(f"  RTF p99           {result['rtf_p99']:.4f}   ({'no chunk misses the deadline' if result['keeps_up'] else 'SOME CHUNKS MISS THE 80 ms DEADLINE'})")
    print(f"  latency mean      {result['latency_mean_ms']:.1f} ms   = {CHUNK_MS:.0f} chunk + {lookahead_ms:.0f} lookahead + {mean_ms:.1f} compute")
    print(f"  latency p99       {result['latency_p99_ms']:.1f} ms   (budget 200-300 ms)")

    out_dir = Path(args.out or f"experiments/results/{date.today().isoformat()}-rtf-cpu")
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "rtf.json").write_text(json.dumps(result, indent=2))
    print(f"\n  written to {out_dir}/rtf.json")


# this gives the scope line for the run-times log: the command line as typed
def run_scope():
    return " ".join(sys.argv[1:])


if __name__ == "__main__":
    with timed("scripts/measure_rtf.py", run_scope):
        main()
