"""Draws the report's delay figure: what each system's word error rate costs in delay, and where that delay comes from.

    ../tse_venv/bin/python scripts/plot_latency.py --out report/figures/latency.pdf

Panel (a) places each system by its mean end-to-end delay and its LCF-WER on the validation set, with a line out to its 99th-percentile delay and its real-time factor in the label.
Panel (b) splits the mean delay into the 80 ms chunk, the 40 ms STFT lookahead (window fill plus one hop, src/models/stft.py) and the computation, against the 200 to 300 ms budget.
Delay figures are the median of the three idle-machine runs of 2026-09-28 (scripts/measure_rtf.py), and WeSep's is its one run of 2026-09-03 (scripts/measure_rtf_wesep.py).
Every run processes chunks without carrying state, so the times are estimates with 10 to 20 % error, as each rtf.json says.
The baseline runs timed the 10000-e6 checkpoint, which has the same architecture and parameter count (7,189,644) as the matched baseline, so its compute time is the same.
The LCF-WER values are the three-run means of the main results table (experiments/results/2026-09-27-judge-plain-sd).
Claude Code wrote this script from the author's figure specification (2026-10-27).
"""

import argparse
import json
from pathlib import Path
from statistics import median

import matplotlib as mpl
import matplotlib.pyplot as plt

# The figure is written straight to a file, without a screen.
mpl.use("Agg")

# House style for every report figure, copied from scripts/plot_training_curves.py. Generated by Claude Code
mpl.rcParams.update({
    "font.family": "serif",
    "font.serif": ["Times New Roman", "Nimbus Roman", "DejaVu Serif"],
    "font.size": 9, "axes.labelsize": 9, "axes.titlesize": 9,
    "xtick.labelsize": 8, "ytick.labelsize": 8, "legend.fontsize": 8,
    "axes.linewidth": 0.6, "xtick.major.width": 0.6, "ytick.major.width": 0.6,
    "axes.spines.top": False, "axes.spines.right": False,
    "figure.dpi": 140, "savefig.dpi": 300,
    "savefig.bbox": "tight", "savefig.pad_inches": 0.01, "pdf.fonttype": 42,
    "mathtext.fontset": "stix",
})
TEXTWIDTH_IN = 6.3
FIGURE_HEIGHT_IN = 2.3
INK = "#222222"
BLUE = "#0B6E99"
ORANGE = "#C1440E"
MUTED = "#6B6B6B"
# WeSep gets its own colour, the same as in the bar figures; reddish purple from the colour-blind-safe palette of Okabe and Ito (2008).
WESEP_COLOUR = "#CC79A7"
SHADE = "#ECECEC"
LIGHT_GREY = "#D9D9D9"
MID_GREY = "#A6A6A6"

RESULTS = Path(__file__).resolve().parents[1] / "experiments/results"

# Each system's timing runs, colour and LCF-WER on the validation set (three-run mean).
SYSTEMS = {
    "Baseline": {"runs": ["2026-09-28-rtf-idle-baseline-r1", "2026-09-28-rtf-idle-baseline-r2", "2026-09-28-rtf-idle-baseline-r3"], "colour": ORANGE, "word_error": 53.26},
    "Extension": {"runs": ["2026-09-28-rtf-idle-e21-r1", "2026-09-28-rtf-idle-e21-r2", "2026-09-28-rtf-idle-e21-r3"], "colour": BLUE, "word_error": 39.59},
    "WeSep": {"runs": ["2026-09-03-rtf-wesep-cpu"], "colour": WESEP_COLOUR, "word_error": 25.80},
}
NO_PROCESSING_WORD_ERROR = 62.94
BUDGET_MS = (200.0, 300.0)


# this reads the median over a system's timing runs of the numbers the figure needs
def read_timing(run_directories):
    chunk_ms = []
    lookahead_ms = []
    compute_ms = []
    delay_ms = []
    delay_p99_ms = []
    real_time_factor = []
    for run_directory in run_directories:
        with open(RESULTS / run_directory / "rtf.json") as handle:
            timing = json.load(handle)
        chunk_ms.append(timing["chunk_ms"])
        lookahead_ms.append(timing["lookahead_ms"])
        compute_ms.append(timing["per_chunk_mean_ms"])
        delay_ms.append(timing["latency_mean_ms"])
        delay_p99_ms.append(timing["latency_p99_ms"])
        real_time_factor.append(timing["rtf_mean"])
    return {"chunk": median(chunk_ms), "lookahead": median(lookahead_ms), "compute": median(compute_ms), "delay": median(delay_ms), "delay_p99": median(delay_p99_ms), "rtf": median(real_time_factor)}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default="report/figures/latency.pdf")
    arguments = parser.parse_args()

    timings = {}
    for name, system in SYSTEMS.items():
        timings[name] = read_timing(system["runs"])

    figure, (axis_error, axis_split) = plt.subplots(1, 2, figsize=(TEXTWIDTH_IN, FIGURE_HEIGHT_IN), gridspec_kw={"width_ratios": [1.0, 1.15], "wspace": 0.35})

    # Panel (a): word error against delay, with the budget shaded.
    axis_error.axvspan(BUDGET_MS[0], BUDGET_MS[1], color=SHADE, zorder=0)
    axis_error.text(sum(BUDGET_MS) / 2, 2, "budget", fontsize=8, color=MUTED, ha="center", va="bottom")
    axis_error.scatter(0, NO_PROCESSING_WORD_ERROR, s=26, marker="s", color=MUTED, zorder=3)
    axis_error.annotate("No processing", (0, NO_PROCESSING_WORD_ERROR), xytext=(7, 0), textcoords="offset points", fontsize=8, color=INK, va="center")
    label_offsets = {"Baseline": (7, 7), "Extension": (7, 0), "WeSep": (-4, 9)}
    label_alignment = {"Baseline": "left", "Extension": "left", "WeSep": "center"}
    for name, system in SYSTEMS.items():
        timing = timings[name]
        axis_error.plot([timing["delay"], timing["delay_p99"]], [system["word_error"], system["word_error"]], color=system["colour"], linewidth=0.9, zorder=2)
        axis_error.scatter(timing["delay"], system["word_error"], s=28, marker="D", color=system["colour"], zorder=3)
        axis_error.annotate(f"{name} (RTF {timing['rtf']:.2f})", (timing["delay"], system["word_error"]), xytext=label_offsets[name], textcoords="offset points", fontsize=8, color=INK, va="center", ha=label_alignment[name])
    axis_error.set_xlim(-20, 600)
    axis_error.set_ylim(0, 70)
    axis_error.set_xlabel("End-to-end delay (ms)")
    axis_error.set_ylabel("LCF-WER (%)")
    axis_error.set_title("(a) Error against delay", loc="left")

    # Panel (b): the mean delay split into its three parts, one bar per system.
    names = list(SYSTEMS.keys())
    for row_number, name in enumerate(names):
        timing = timings[name]
        axis_split.barh(row_number, timing["chunk"], color=LIGHT_GREY, height=0.55, label="80 ms chunk" if row_number == 0 else None)
        axis_split.barh(row_number, timing["lookahead"], left=timing["chunk"], color=MID_GREY, height=0.55, label="40 ms STFT lookahead" if row_number == 0 else None)
        axis_split.barh(row_number, timing["compute"], left=timing["chunk"] + timing["lookahead"], color=SYSTEMS[name]["colour"], height=0.55)
        axis_split.text(timing["delay"] + 8, row_number, f"{timing['delay']:.0f} ms", fontsize=8, color=INK, va="center", ha="left")
    for budget_edge in BUDGET_MS:
        axis_split.axvline(budget_edge, color=MUTED, linestyle="--", linewidth=0.7, zorder=0)
    axis_split.set_yticks(range(len(names)))
    axis_split.set_yticklabels(names)
    axis_split.set_ylim(len(names) - 0.5, -0.9)
    axis_split.tick_params(axis="y", length=0)
    axis_split.set_xlim(0, 420)
    axis_split.set_xlabel("Mean delay (ms); computation in colour")
    axis_split.set_title("(b) Where the delay goes", loc="left")
    axis_split.legend(loc="upper right", frameon=False, handlelength=1.2, borderaxespad=0.0)

    output_path = Path(arguments.out)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(output_path)
    print(f"wrote {output_path}")
    # Print the plotted values so they can be checked against the latency runs. Generated by Claude Code
    for name, timing in timings.items():
        print(f"{name:10s} chunk {timing['chunk']:5.1f}  lookahead {timing['lookahead']:5.1f}  compute {timing['compute']:6.1f}  delay {timing['delay']:6.1f}  p99 {timing['delay_p99']:6.1f}  RTF {timing['rtf']:.3f}")


if __name__ == "__main__":
    main()
