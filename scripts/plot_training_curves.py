"""Draws the report's training-curve figure: the baseline and the extension on shared epoch axes.

    ../tse_venv/bin/python scripts/plot_training_curves.py --out report/figures/training_curves.pdf

The top row splits the target-present loss into its three weighted terms, L_pres, w_m L_MR and w_g L_gain. The middle row is the word error rate on the 103 sir0_val `both` trials, one diamond per live-judge run and each run's in-training Whisper probe as a thin line.
The bottom row is the two terms the presence gate adds to the loss, from the jointly trained gate run, cut at the extension's last epoch.
Colour is the run (baseline orange, extension blue) and line style is the split (training dashed, validation solid). Epochs where either run fails the silence bar are shaded.
The weights and the silence bar are read from each run's own config copy. The chosen epochs are given, because both were picked on the judge (decisions-m2.md 2026-09-26 and 2026-10-07).
Judge results are found by pattern and checked to be sir0_val / both / 103 trials, so a new evaluation appears without editing this file.
"""

import argparse
import csv
import json
from pathlib import Path
from statistics import mean

import matplotlib as mpl
import matplotlib.pyplot as plt
import yaml
from matplotlib.lines import Line2D
from matplotlib.ticker import MultipleLocator

# The figure is written straight to a file, without a screen.
mpl.use("Agg")

# House style for every report figure. Generated by Claude Code
mpl.rcParams.update({
    "font.family": "serif",
    "font.serif": ["Times New Roman", "Nimbus Roman", "DejaVu Serif"],
    "font.size": 9, "axes.labelsize": 9, "axes.titlesize": 9,
    "xtick.labelsize": 8, "ytick.labelsize": 8, "legend.fontsize": 8,
    "axes.linewidth": 0.6, "xtick.major.width": 0.6, "ytick.major.width": 0.6,
    "axes.spines.top": False, "axes.spines.right": False,
    "figure.dpi": 140, "savefig.dpi": 300,
    "savefig.bbox": "tight", "savefig.pad_inches": 0.01, "pdf.fonttype": 42,
    "mathtext.fontset": "stix",
})
TEXTWIDTH_IN = 6.3
INK = "#222222"
BLUE = "#0B6E99"
ORANGE = "#C1440E"
MUTED = "#6B6B6B"
SHADE = "#ECECEC"
FIGURE_HEIGHT_IN = 5.3
LOSS_YLABEL = "Loss term\n(lower is better)"

RESULTS = Path(__file__).resolve().parents[1] / "experiments/results"

# The extension's judged epochs, which the matched baseline reuses.
JUDGED_EPOCHS = (13, 15, 18, 21, 27)
# The baseline's extra judged epochs. Its chosen epoch is the lowest LCF-WER among all of them (author's decision 2026-10-09).
BASELINE_EXTRA_JUDGED = (4, 5, 11)
# Both runs' second Kaggle session starts at epoch 14.
RESUME = 13.5

# The rows from top to bottom. A row with several panels is split across the width.
ROWS = [["pres", "mr", "gain"], ["wer"], ["gkl", "gbce"]]
GATE_PANELS = ("gkl", "gbce")


# this lists the folder patterns that hold the judge runs of each epoch
def judge_patterns(stem, epochs):
    patterns = {}
    for epoch in epochs:
        patterns[epoch] = [f"*-eval-{stem}-e{epoch}-judge", f"*-eval-{stem}-e{epoch}-judge-r*"]
    return patterns


# The two compared runs, drawn in this order. On an epoch both runs scored, the first is nudged left.
RUNS = {
    "Baseline": {
        "label": "Baseline, matched protocol",
        "colour": ORANGE,
        "history": ["2026-10-07-train-sir0-baseline-matched-s1"],
        "chosen": 11,
        # One diamond at this epoch, the lowest of its judge runs (author's choice 2026-10-09). The report's judge table gives the mean of three runs.
        "lowest_run_only": (11,),
        "lowest_marker": False,
        "judge": judge_patterns("baseline-matched", BASELINE_EXTRA_JUDGED + JUDGED_EPOCHS),
    },
    "Extension": {
        "label": "Extension",
        "colour": BLUE,
        "history": ["2026-09-24-train-sir0-cuecontext-wer", "2026-09-24-train-sir0-cuecontext-wer-resume"],
        "chosen": 21,
        "lowest_run_only": (),
        "lowest_marker": True,
        "judge": judge_patterns("cuecontext-wer", JUDGED_EPOCHS),
    },
}

# The jointly trained presence gate, arm A (decisions-m2.md 2026-10-14 to 2026-10-18). It is drawn only in the bottom row.
GATE = {
    "colour": BLUE,
    "history": ["2026-10-16-train-sir0-presence-gate-A", "2026-10-16-train-sir0-presence-gate-A-resume", "2026-10-18-train-sir0-presence-gate-A-resume2"],
    "resumes": (12.5, 25.5),
}


# this is the separation term
def separation_term(row, prefix, config):
    return float(row[prefix + "L_pres"])


# this is the spectrum term with its weight
def spectrum_term(row, prefix, config):
    return float(config["loss"]["w_m"]) * float(row[prefix + "L_MR"])


# this is the level term with its weight
def level_term(row, prefix, config):
    return float(config["loss"]["w_g"]) * float(row[prefix + "L_gain"])


# this is the gate's prior term with its weight
def gate_prior_term(row, prefix, config):
    return float(config["loss"]["presence"]["beta"]) * float(row[prefix + "L_kl"])


# this is the gate's label term with its weight
def gate_label_term(row, prefix, config):
    return float(config["loss"]["presence"]["lam"]) * float(row[prefix + "L_bce"])


# The loss panels. The three top panels add up to the target-present loss.
PANELS = {
    "pres": {"title": r"Separation, $L_\mathrm{pres}$", "term": separation_term},
    "mr": {"title": r"Spectrum, $w_\mathrm{m} L_\mathrm{MR}$", "term": spectrum_term},
    "gain": {"title": r"Level, $w_\mathrm{g} L_\mathrm{gain}$", "term": level_term},
    "gkl": {"title": r"Gate prior, $\beta\,\mathrm{KL}(q\,\|\,p)$", "term": gate_prior_term},
    "gbce": {"title": r"Gate labels, $\lambda\,\mathrm{BCE}$", "term": gate_label_term},
}


# this finds the training config a run copied into its results folder
def run_config(run_directory):
    for path in sorted(run_directory.glob("*.yaml")):
        config = yaml.safe_load(path.read_text())
        if isinstance(config, dict) and "loss" in config and "training" in config:
            return config
    raise FileNotFoundError(f"no training config in {run_directory}")


# this is the whole target-present loss, the number the lowest-loss marker is placed on
def present_branch(row, prefix, config):
    return separation_term(row, prefix, config) + spectrum_term(row, prefix, config) + level_term(row, prefix, config)


# this reads the LCF-WER of every judge run matching the patterns, after checking each is the headline set
def scored_runs(patterns):
    run_directories = set()
    for pattern in patterns:
        for path in RESULTS.glob(pattern):
            run_directories.add(path)
    values = []
    for directory in sorted(run_directories):
        results = json.loads((directory / "results.json").read_text())
        if (results["split"], results["condition"], results["n_trials"]) != ("sir0_val", "both", 103):
            raise SystemExit(f"{directory.name} is not sir0_val / both / 103")
        values.append(float(results["systems"]["estimate"]["lcf_wer"]))
    return values


# this joins a run's sessions into one history and checks they trained under the same loss
def load_history(name, spec):
    rows = []
    configs = []
    for directory_name in spec["history"]:
        run_directory = RESULTS / directory_name
        for row in csv.DictReader((run_directory / "history.csv").open()):
            rows.append(row)
        configs.append(run_config(run_directory))
    for config in configs[1:]:
        if (config["loss"], config["training"]["select_abs_max"]) != (configs[0]["loss"], configs[0]["training"]["select_abs_max"]):
            raise SystemExit(f"{name}: sessions disagree on the loss config")
    return rows, configs[0]


# this gathers every judged epoch of a run and its judge scores
def judge_scores(spec):
    judged = {}
    for epoch, patterns in spec["judge"].items():
        values = scored_runs(patterns)
        if values:
            judged[epoch] = values
    for epoch in spec["lowest_run_only"]:
        if epoch in judged:
            judged[epoch] = [min(judged[epoch])]
    return judged


# this nudges overlapping labels upward until none overlap, so each label stays beside its own diamond. Generated by Claude Code
def separate(texts, axis):
    renderer = axis.figure.canvas.get_renderer()
    y_bottom, y_top = axis.get_ylim()
    units_per_pixel = (y_top - y_bottom) / axis.get_window_extent(renderer).height
    for attempt in range(100):
        boxes = []
        for text in texts:
            boxes.append(text.get_window_extent(renderer))
        order = sorted(range(len(texts)), key=lambda index: boxes[index].y0)
        clash = None
        for position, lower in enumerate(order):
            for upper in order[position + 1:]:
                if boxes[lower].overlaps(boxes[upper]):
                    clash = (lower, upper)
                    break
            if clash is not None:
                break
        if clash is None:
            return
        lower, upper = clash
        x, y = texts[upper].get_position()
        texts[upper].set_position((x, y + (boxes[lower].y1 - boxes[upper].y0 + 2) * units_per_pixel))


# this is where the figure is drawn. Generated by Claude Code
def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    loaded = {}
    for name, spec in RUNS.items():
        rows, config = load_history(name, spec)
        loaded[name] = (rows, config, judge_scores(spec))
    bars = set()
    last_epoch = 0
    for rows, config, judged in loaded.values():
        bars.add(float(config["training"]["select_abs_max"]))
        last_epoch = max(last_epoch, int(rows[-1]["epoch"]))
    if len(bars) != 1:
        raise SystemExit(f"runs disagree on the silence bar: {sorted(bars)}")
    bar = bars.pop()
    failing_epochs = set()
    for rows, config, judged in loaded.values():
        for row in rows:
            if float(row["val_L_abs"]) > bar:
                failing_epochs.add(int(row["epoch"]))

    # One grid row per figure row. Every panel shares the epoch axis.
    figure = plt.figure(figsize=(TEXTWIDTH_IN, FIGURE_HEIGHT_IN))
    grid = figure.add_gridspec(len(ROWS), 1, hspace=0.25)
    axes = {}
    first_axis = None
    for row_index, names in enumerate(ROWS):
        cells = grid[row_index].subgridspec(1, len(names), wspace=0.35)
        for column, panel in enumerate(names):
            axes[panel] = figure.add_subplot(cells[0, column], sharex=first_axis)
            if first_axis is None:
                first_axis = axes[panel]
    wer = axes["wer"]
    # The panels of the two compared runs, and the loss panels among them.
    run_axes = {}
    loss_panels = []
    for panel, axis in axes.items():
        if panel not in GATE_PANELS:
            run_axes[panel] = axis
            if panel != "wer":
                loss_panels.append(panel)

    for axis in run_axes.values():
        for epoch in sorted(failing_epochs):
            axis.axvspan(epoch - 0.5, epoch + 0.5, color=SHADE, lw=0, zorder=0)
        axis.axvline(RESUME, color=MUTED, lw=0.6, ls=(0, (1, 2)), zorder=1)
    wer.text(RESUME - 0.3, 0.03, "session 2", transform=wer.get_xaxis_transform(), ha="right", va="bottom", fontsize=7, color=MUTED)

    marks = {}  # epoch to a list of (run index, run name, judge scores), for dodging and labels
    chosen_labels = []
    for run_index, (name, spec) in enumerate(RUNS.items()):
        rows, config, judged = loaded[name]
        colour = spec["colour"]
        epochs = []
        for row in rows:
            epochs.append(int(row["epoch"]))

        for panel in loss_panels:
            term = PANELS[panel]["term"]
            train_values = []
            val_values = []
            for row in rows:
                train_values.append(term(row, "train_", config))
                val_values.append(term(row, "val_", config))
            axes[panel].plot(epochs, train_values, "--", color=colour, lw=1.1, zorder=3)
            axes[panel].plot(epochs, val_values, "o-", color=colour, lw=1.3, ms=2.6, zorder=3)
        probe_values = []
        for row in rows:
            probe_values.append(float(row["val_content_wer"]))
        wer.plot(epochs, probe_values, "-", color=colour, lw=0.8, alpha=0.55, zorder=2)

        chosen = spec["chosen"]
        for axis in run_axes.values():
            axis.axvline(chosen, color=colour, lw=0.8, zorder=2)
        chosen_labels.append((chosen, f"{name.lower()} chosen ({chosen})"))
        if spec["lowest_marker"]:
            # The lowest validation loss is always the whole target-present loss, and its circle sits on the first loss panel.
            val_present = []
            for row in rows:
                val_present.append(present_branch(row, "val_", config))
            lowest = min(range(len(epochs)), key=lambda index: val_present[index])
            for axis in run_axes.values():
                axis.axvline(epochs[lowest], color=colour, lw=0.7, ls="--", zorder=2)
            first_panel = loss_panels[0]
            axes[first_panel].plot(epochs[lowest], PANELS[first_panel]["term"](rows[lowest], "val_", config), "o", ms=7, mfc="none", mec=colour, mew=1.0, zorder=4)
            wer.text(epochs[lowest] + 0.4, 0.03, f"{name.lower()} lowest\nvalidation loss ({epochs[lowest]})", transform=wer.get_xaxis_transform(), ha="left", va="bottom", fontsize=7, color=INK)

        for epoch, values in judged.items():
            marks.setdefault(epoch, []).append((run_index, name, values))
        judged_text = []
        for epoch in sorted(judged):
            rounded = []
            for value in judged[epoch]:
                rounded.append(round(value, 2))
            judged_text.append(f"e{epoch} {rounded}")
        print(f"{name}: epochs {epochs[0]}-{epochs[-1]}, chosen {chosen}, judged " + ", ".join(judged_text))

    # The gate row: the gate run alone, cut at the figure's last epoch, with its own session breaks. Its silence-bar failures are not shaded, because the shading belongs to the two compared runs.
    all_gate_rows, gate_config = load_history("Gate", GATE)
    if "presence" not in gate_config["loss"]:
        raise SystemExit("gate run's config has no loss.presence block")
    gate_rows = []
    gate_epochs = []
    for row in all_gate_rows:
        if int(row["epoch"]) <= last_epoch:
            gate_rows.append(row)
            gate_epochs.append(int(row["epoch"]))
    for panel in GATE_PANELS:
        axis = axes[panel]
        for resume in GATE["resumes"]:
            if resume < last_epoch:
                axis.axvline(resume, color=MUTED, lw=0.6, ls=(0, (1, 2)), zorder=1)
        term = PANELS[panel]["term"]
        train_values = []
        val_values = []
        for row in gate_rows:
            train_values.append(term(row, "train_", gate_config))
            val_values.append(term(row, "val_", gate_config))
        axis.plot(gate_epochs, train_values, "--", color=GATE["colour"], lw=1.1, zorder=3)
        axis.plot(gate_epochs, val_values, "o-", color=GATE["colour"], lw=1.3, ms=2.6, zorder=3)
    print(f"Gate: epochs {gate_epochs[0]}-{gate_epochs[-1]} of {int(all_gate_rows[-1]['epoch'])} drawn, beta {gate_config['loss']['presence']['beta']}, lambda {gate_config['loss']['presence']['lam']}")

    # The earlier chosen line is labelled on its left, so the two labels share the top line without touching.
    chosen_labels.sort()
    for label_index, (x, text) in enumerate(chosen_labels):
        left = len(chosen_labels) == 1 or label_index == 0
        if left:
            wer.text(x - 0.3, 0.98, text, transform=wer.get_xaxis_transform(), ha="right", va="top", fontsize=7, color=INK)
        else:
            wer.text(x + 0.3, 0.98, text, transform=wer.get_xaxis_transform(), ha="left", va="top", fontsize=7, color=INK)

    # The diamonds. Where both runs scored an epoch they are nudged apart and each labels on its own side, first run left and second right.
    # A lone run labels on the right unless the next scored epoch is closer than 3 or this is the last epoch. Any overlap left after that is separated vertically.
    scored = sorted(marks)
    texts = []
    right_edge = last_epoch + 0.5
    label_box = {"boxstyle": "square,pad=0.1", "fc": "white", "ec": "none"}
    for position, epoch in enumerate(scored):
        runs_here = set()
        for mark in marks[epoch]:
            runs_here.add(mark[0])
        runs_here = sorted(runs_here)
        shared = len(runs_here) > 1
        dodge = {}
        for order, run_index in enumerate(runs_here):
            dodge[run_index] = (order - (len(runs_here) - 1) / 2) * 0.4
        crowded = epoch == last_epoch or (position + 1 < len(scored) and scored[position + 1] - epoch < 3)
        # With neighbours within 2 epochs on both sides, a side label would sit on a neighbour's diamond, so the label goes above its own diamonds instead.
        boxed_in = crowded and position > 0 and epoch - scored[position - 1] < 3
        for run_index, name, values in marks[epoch]:
            colour = RUNS[name]["colour"]
            x = epoch + dodge[run_index]
            wer.plot([x] * len(values), values, "D", color=colour, ms=4.5, mew=0, alpha=0.9, zorder=4)
            if boxed_in and not shared:
                texts.append(wer.text(x, max(values) + 2.0, f"{mean(values):.1f}", ha="center", va="bottom", fontsize=7, zorder=6, color=INK, bbox=label_box))
                continue
            if shared:
                left = dodge[run_index] < 0
            else:
                left = crowded
            if left:
                texts.append(wer.text(x - 0.45, mean(values), f"{mean(values):.1f}", ha="right", va="center", fontsize=7, zorder=6, color=INK, bbox=label_box))
            else:
                right_edge = max(right_edge, x + 1.6)
                texts.append(wer.text(x + 0.45, mean(values), f"{mean(values):.1f}", ha="left", va="center", fontsize=7, zorder=6, color=INK, bbox=label_box))

    for panel in ROWS[-1]:
        axes[panel].set_xlabel("Epoch")
    wer.xaxis.set_major_locator(MultipleLocator(2 if last_epoch < 16 else 4))
    wer.xaxis.set_minor_locator(MultipleLocator(1))
    wer.set_xlim(-0.5, right_edge)
    wer.set_ylim(15, 80)
    separate(texts, wer)
    for panel in loss_panels + list(GATE_PANELS):
        axes[panel].set_title(PANELS[panel]["title"], fontsize=8)
    axes[ROWS[0][0]].set_ylabel(LOSS_YLABEL)
    axes[ROWS[-1][0]].set_ylabel(LOSS_YLABEL)
    wer.set_ylabel("Word error rate\n(%, lower is better)")
    # The word-error row is the only single-panel row above the bottom, and a split row keeps its own epoch ticks.
    wer.tick_params(labelbottom=False)

    # The legend sits just under the bottom row's "Epoch" label, in three columns of two: runs, line styles, word error.
    figure.canvas.draw()
    epoch_label = axes[ROWS[-1][0]].xaxis.label.get_window_extent(figure.canvas.get_renderer())
    legend_y = figure.transFigure.inverted().transform((0, epoch_label.y0))[1] - 0.01
    handles = []
    labels = []
    for spec in RUNS.values():
        handles.append(Line2D([], [], color=spec["colour"], ls="-", marker="o", ms=2.6, lw=1.3))
        labels.append(spec["label"])
    handles.append(Line2D([], [], color=INK, ls="-", lw=1.3))
    handles.append(Line2D([], [], color=INK, ls="--", lw=1.1))
    handles.append(Line2D([], [], color=MUTED, lw=0.8))
    handles.append(Line2D([], [], color=MUTED, ls="none", marker="D", ms=4.5, mew=0))
    labels.extend(["Validation", "Training", "Whisper in training (40 clips)", "Gemini, one per run (103 trials)"])
    figure.legend(handles=handles, labels=labels, loc="upper center", bbox_to_anchor=(0.5, legend_y), ncol=3, frameon=False, handlelength=2.2, columnspacing=1.4)
    first_column = []
    for names in ROWS:
        first_column.append(axes[names[0]])
    figure.align_ylabels(first_column)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(args.out)
    plt.close(figure)
    print(args.out)


if __name__ == "__main__":
    main()
